export type SearchBuilder = {
  url: string;
  post: boolean;
  auth: boolean;
  apiKey: string;
  queryKey: string;
  sendLimit: boolean;
  limitKey: string;
  results: string;
  title: string;
  link: string;
  snippet: string;
  filter: boolean;
  dedupe: boolean;
  limit: boolean;
  scrape: boolean;
};
export const defaultSearchBuilder: SearchBuilder = {
  url: "",
  post: false,
  auth: false,
  apiKey: "",
  queryKey: "q",
  sendLimit: true,
  limitKey: "limit",
  results: "results",
  title: "title",
  link: "url",
  snippet: "snippet",
  filter: true,
  dedupe: true,
  limit: true,
  scrape: false,
};
// QuickJS on Android exposes synchronous fetch, rather than browser Promises.
export function buildSearchScripts(c: SearchBuilder) {
  const url = new URL(c.url);
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password || url.hash)
    throw new Error("搜索地址必须是 HTTP/HTTPS 地址");
  if (!c.queryKey.trim() || (c.sendLimit && !c.limitKey.trim()) || (c.auth && !c.apiKey.trim()))
    throw new Error("请填写带 * 的必填项");
  const q = JSON.stringify;
  return {
    searchScript: `// Generated by RikkaHub visual search builder. Synchronous Android fetch.
function search(query, resultSize) {
  var params = Object.create(null);
  params[${q(c.queryKey)}] = query;
  ${c.sendLimit ? `params[${q(c.limitKey)}] = resultSize;` : ""}
  var headers = ${q(c.auth ? { Authorization: `Bearer ${c.apiKey}` } : {})};
  var url = ${q(c.url)};
  var options = { method: ${q(c.post ? "POST" : "GET")}, headers: headers };
  ${c.post ? 'headers["Content-Type"] = "application/json"; options.body = JSON.stringify(params);' : 'url += (url.indexOf("?") < 0 ? "?" : "&") + Object.keys(params).map(function(k) { return encodeURIComponent(k) + "=" + encodeURIComponent(params[k]); }).join("&");'}
  var response = fetch(url, options);
  if (!response.ok) throw new Error("Search HTTP " + response.status);
  function path(obj, key) { return key ? key.split(".").reduce(function(v, k) { return v == null ? undefined : v[k]; }, obj) : obj; }
  var rows = path(response.json(), ${q(c.results)});
  if (!Array.isArray(rows)) throw new Error("结果列表路径不是数组");
  var seen = Object.create(null);
  var items = rows.map(function(r) { return { title: String(path(r, ${q(c.title)}) || ""), url: String(path(r, ${q(c.link)}) || ""), text: String(path(r, ${q(c.snippet)}) || "") }; });
  ${c.filter ? "items = items.filter(function(r) { return /^https?:\\/\\//i.test(r.url); });" : ""}
  ${c.dedupe ? "items = items.filter(function(r) { if (seen[r.url]) return false; seen[r.url] = true; return true; });" : ""}
  return { items: ${c.limit ? "items.slice(0, resultSize)" : "items"} };
}`,
    scrapeScript: c.scrape
      ? `function scrape(urls) {
  return { urls: urls.map(function(url) {
    if (!/^https?:\\/\\//i.test(url)) throw new Error("Unsupported URL");
    var response = fetch(url);
    if (!response.ok) throw new Error("Scrape HTTP " + response.status);
    return { url: url, content: response.text() };
  }) };
}`
      : "",
  };
}
